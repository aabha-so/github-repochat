import os
from datetime import datetime
from github_loader import clone_repository, get_repo_name
from retriever import load_faiss_index
from agent import answer_with_agent

def generate_repo_wiki(repo_name, index, chunks):
    """
    Generates a structured markdown wiki for a repository by asking a fixed set
    of questions through the agent and compiling the answers.
    """
    # Define the fixed sections and their corresponding questions
    sections = {
        "Overview": "What is this repository about? Summarize its purpose in 2-3 sentences.",
        "Architecture": "Explain how this project's code is organized. What are the main modules or components?",
        "Setup & Usage": "How do I install dependencies and run this project?",
        "Key Dependencies": "What are the main libraries or frameworks this project depends on?",
        "Configuration": "Are there any important configuration files in this project, and what do they control?"
    }

    wiki_content = f"# Wiki: {repo_name}\n"
    wiki_content += f"Generated by GitHubMP Wiki Generator on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"

    for section_title, question in sections.items():
        print(f"Generating {section_title} section...")

        # Call the existing agent function
        result = answer_with_agent(question, index, chunks)

        answer_text = result["answer"]
        sources = result["sources"]

        wiki_content += f"## {section_title}\n"
        wiki_content += f"{answer_text}\n\n"

        # Add sources if they exist and are not empty
        if sources:
            # Use a set to get unique file paths
            unique_sources = sorted(list(set(sources)))
            sources_str = ", ".join([f"`{s}`" for s in unique_sources])
            wiki_content += f"*Sources: {sources_str}*\n\n"
        else:
            wiki_content += "\n"

    return wiki_content

if __name__ == "__main__":
    # 1. Prompt for repo URL
    url = input("Enter a public GitHub repository URL to generate a wiki for: ").strip()
    if not url:
        print("URL cannot be empty.")
        exit(1)

    try:
        # 2. Clone repo (safe no-op if already exists)
        clone_repository(url)

        # 3. Get repo name
        repo_name = get_repo_name(url)

        # 4. Load FAISS index and chunks
        print(f"Loading FAISS index for {repo_name}...")
        index, loaded_chunks = load_faiss_index(repo_name)

        # 5. Generate the wiki
        print("\nStarting wiki generation. This may take a few minutes as it calls the LLM for each section...\n")
        wiki_markdown = generate_repo_wiki(repo_name, index, loaded_chunks)

        # 6. Save to file
        output_filename = f"{repo_name}_wiki.md"
        with open(output_filename, "w", encoding="utf-8") as f:
            f.write(wiki_markdown)

        print(f"\nSuccess! Wiki generated and saved to {output_filename}")

    except Exception as e:
        print(f"An error occurred: {e}")
